import { launch } from './launch.mjs';
const out = process.argv[2];
const { server, base, browser } = await launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.on('pageerror', (e) => console.error('pageerror', e.message));
await page.goto(base + (process.argv[3] ?? '?title=0&talk=house'));
await page.waitForFunction(() => window.__mwReady === true, null, { timeout: 300000 });
await page.addStyleTag({ content: '#loading{display:none!important}' });
const topics = await page.$$eval('.talk .topics button', (b) => b.map((x) => x.textContent));
console.log('topics', topics);
const i = topics.findIndex((t) => /strange|lately/i.test(t));
await page.click(`.talk .topics button >> nth=${i}`);
await page.waitForTimeout(1700);
await page.screenshot({ path: `${out}/handover.png` });
await page.waitForTimeout(3000);
await page.keyboard.press('Escape');
await page.waitForTimeout(500);
await page.keyboard.press('KeyM');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/map.png` });
await browser.close(); server.close();
